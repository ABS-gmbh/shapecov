#!/usr/bin/env python3
"""Per-shape roll-up of the recorded replays: which corpus shapes each indexer mishandles or drops.

  python3 harness/replay/shapes.py           write harness/replay/SHAPES.md
  python3 harness/replay/shapes.py --check   exit 1 if SHAPES.md differs from what the results give

Reads the committed replay results of each indexer (out/results.jsonl for wallet-backend,
out-stellar-etl/results.jsonl), the named shapes in corpus/patterns.json and the shapes each entry
carries in corpus/manifest.json. For each indexer it takes its current commit, the one the most
entries were replayed at, and gives one row per shape: the entries that carry it, how many of them
passed on every input, and for each that did not, its verdict and the upstream issues that explain
it.

An entry passes when the harness's result is `pass` (the indexer ingested the ledger, stored only
readable addresses and met the manifest's expectations) and the ledger-state oracle found no failing
row. Otherwise the cell gives the harness result (`mishandled` or `dropped`) or, when only the oracle
failed, `oracle`, with the oracle's issue labels. A ledger carries several shapes and its verdict is
listed under each; the table does not say which shape caused a failure. Standard library only.
"""
import json
import os
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "SHAPES.md")
INDEXERS = [("wallet-backend", "out/results.jsonl"), ("stellar-etl", "out-stellar-etl/results.jsonl")]


def load(path):
    with open(path) as f:
        return json.load(f)


def carriers():
    """{pattern: [entry ids]} for every pattern in corpus/patterns.json."""
    patterns = load(os.path.join(REPO, "corpus/patterns.json"))["patterns"]
    out = {p: [] for p in patterns}
    for e in load(os.path.join(REPO, "corpus/manifest.json"))["entries"]:
        for x in e.get("patterns") or []:
            name = x if isinstance(x, str) else (x.get("pattern") or x.get("name"))
            out.setdefault(name, []).append(e["id"])
    return patterns, out


def verdict(r):
    """(word, issue labels) for one replay of one entry on one input."""
    if r["result"] == "not applicable":
        return "not applicable", []
    o = r.get("oracle") or {}
    labels = sorted(o.get("known") or {})
    if o.get("unexplained"):
        labels.append("unexplained")
    if r["result"] != "pass":
        return r["result"], labels
    if o.get("verdict") not in (None, "pass"):
        return "oracle", labels
    return "pass", []


def current(rows):
    """The commit with the most replayed entries."""
    by = Counter()
    seen = set()
    for r in rows:
        if (r["commit"], r["entry_id"]) not in seen:
            seen.add((r["commit"], r["entry_id"]))
            by[r["commit"]] += 1
    return min(by, key=lambda c: (-by[c], c)) if by else None


def per_entry(rows, commit):
    """{entry: {input: (word, labels)}} at one commit."""
    out = defaultdict(dict)
    for r in rows:
        if r["commit"] == commit:
            out[r["entry_id"]][r["input"]] = verdict(r)
    return out


def cell(inputs):
    """One entry's verdict across its inputs, e.g. 'oracle: stellar/wallet-backend#815'."""
    words = {(w, tuple(labels)) for w, labels in inputs.values()}
    if len(words) == 1:
        (w, labels), = words
        return w + (": " + ", ".join(labels) if labels else "")
    return "; ".join("%s %s%s" % (i, w, ": " + ", ".join(lb) if lb else "") for i, (w, lb) in sorted(inputs.items()))


def render():
    patterns, carry = carriers()
    L = ["# Shapes each indexer mishandles or drops", "",
         "Generated by `harness/replay/shapes.py` from the committed replay results; do not edit by hand. "
         "One row per named shape in `corpus/patterns.json`, for each indexer at the commit the most corpus "
         "entries were replayed at. Per entry and commit, the full results are in [`RESULTS.md`](RESULTS.md) "
         "and [`RESULTS-stellar-etl.md`](RESULTS-stellar-etl.md).", "",
         "An entry passes when the harness's result is `pass` and the ledger-state oracle found no failing row, "
         "on every input. Otherwise the table gives the harness result (`mishandled` or `dropped`) or, when only "
         "the oracle failed, `oracle`, with the upstream issues that explain it (`unexplained` would be a "
         "candidate finding). A ledger carries several shapes, and its verdict is listed under each, so a row "
         "does not say that its shape caused the failure; the issue does.", ""]
    for name, rel in INDEXERS:
        path = os.path.join(HERE, rel)
        with open(path) as f:
            rows = [json.loads(line) for line in f]
        commit = current(rows)
        entries = per_entry(rows, commit)
        ok_shapes = n_shapes = 0
        body = []
        for p in sorted(patterns):
            ids = carry.get(p, [])
            run = [e for e in ids if e in entries and any(w != "not applicable" for w, _ in entries[e].values())]
            failing = [e for e in run if any(w != "pass" for w, _ in entries[e].values())]
            if ids:
                n_shapes += bool(run)
                ok_shapes += bool(run) and not failing
            if not ids:
                status = "no corpus entry yet"
            elif not run:
                status = "not replayed (%s)" % ("not applicable: network" if any(e in entries for e in ids)
                                                else "not in this indexer's run")
            elif not failing:
                status = "pass"
            else:
                groups = defaultdict(list)
                for e in sorted(failing):
                    groups[cell(entries[e])].append(e)
                status = "; ".join("%s (%d): %s" % (v, len(es), ", ".join("`%s`" % e for e in es))
                                   for v, es in sorted(groups.items()))
            body.append("| `%s` | %d | %d | %d | %s |" % (p, len(ids), len(run), len(run) - len(failing), status))
        by_issue = Counter(label for e in entries.values()
                           for label in {lb for w, labels in e.values() if w != "pass" for lb in labels})
        failing_entries = sum(1 for e in entries.values() if any(w not in ("pass", "not applicable") for w, _ in e.values()))
        L += ["## %s at `%s`" % (name, commit[:12]), "",
              "%d of the %d shapes replayed pass on every entry that carries them. %d of the %d entries replayed "
              "fail somewhere; by issue: %s." % (
                  ok_shapes, n_shapes, failing_entries,
                  sum(1 for e in entries.values() if any(w != "not applicable" for w, _ in e.values())),
                  ", ".join("%s on %d" % (k, v) for k, v in sorted(by_issue.items(), key=lambda kv: (-kv[1], kv[0])))
                  or "none"), "",
              "| Shape | Entries | Replayed | Pass | Verdict and issue where not a pass |",
              "|---|---|---|---|---|"] + body + [""]
    return "\n".join(L)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        with open(OUT) as f:
            if f.read() != text:
                print("SHAPES.md differs from the recorded results; run python3 harness/replay/shapes.py")
                return 1
        print("SHAPES OK: harness/replay/SHAPES.md is current")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote harness/replay/SHAPES.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
