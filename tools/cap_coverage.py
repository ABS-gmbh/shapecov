#!/usr/bin/env python3
"""Per-CAP coverage: check corpus/cap-coverage.json against the corpus and write corpus/CAP-COVERAGE.md.

  cap_coverage.py [--check]

For every live CAP the file gives either the evidence that shows it in ledger data (schema cells,
named patterns, data probes) or the reason it has no reader-visible shape. This finds, for each
piece of evidence, the corpus entries that contain it, classifies the CAP and writes the table:

  covered          every piece of evidence is in at least one corpus entry
  partly covered   some is; the rest is listed as a gap with the planned entry
  gap              none is
  no shape         no reader-visible shape (the reason is given)

--check fails if a cell named as evidence does not exist in the schema, or if the table on disk is
out of date.

Probes are shapes a schema cell cannot name; each walks every decoded LedgerCloseMeta:
  trustline_authorized_to_maintain_liabilities  a trustline whose flags include
                                                AUTHORIZED_TO_MAINTAIN_LIABILITIES (CAP-0018)
  preauth_signer_removed_in_failed_tx           a pre-authorized-transaction signer removed by a
                                                failed transaction (CAP-0028)
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import oracle  # noqa: E402
from gen import all_cells  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"


def probe_hits(manifest):
    hits = {"trustline_authorized_to_maintain_liabilities": [], "preauth_signer_removed_in_failed_tx": []}
    for e in manifest["entries"]:
        if e.get("xdr_type") != "LedgerCloseMeta":
            continue
        _, value = oracle.load_entry(e["id"])
        found = set()

        def walk(x):
            if isinstance(x, dict):
                tl = x.get("trustLine")
                if isinstance(tl, dict) and isinstance(tl.get("flags"), int) and tl["flags"] & 2:
                    found.add("trustline_authorized_to_maintain_liabilities")
                for v in x.values():
                    walk(v)
            elif isinstance(x, list):
                for v in x:
                    walk(v)
        walk(value)
        for c in oracle.changes(value):
            if c["what"] == "signer" and c["how"] == "removed" and not c["success"] and c["signer"].startswith("T"):
                found.add("preauth_signer_removed_in_failed_tx")
        for p in found:
            hits[p].append(e["id"])
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    spec = json.load(open(CORPUS / "cap-coverage.json"))
    manifest = json.load(open(CORPUS / "manifest.json"))
    schema_cells = all_cells(json.load(open(ROOT / "schema" / "schema.json")))
    by_cell, by_pattern = {}, {}
    for e in manifest["entries"]:
        for c in e.get("cells", []):
            by_cell.setdefault(c, []).append(e["id"])
        for p in e.get("patterns") or {}:
            by_pattern.setdefault(p, []).append(e["id"])
    probes = probe_hits(manifest)
    errors, rows, counts = [], [], {}
    for c in spec["caps"]:
        if "no_shape_reason" in c:
            status, shown, missing = "no shape", [], []
        else:
            shown, missing = [], []
            ev = c["evidence"]
            for cell in ev.get("cells", []):
                if cell not in schema_cells:
                    errors.append("%s: %s is not a schema cell" % (c["cap"], cell))
                (shown if by_cell.get(cell) else missing).append(("`%s`" % cell, len(by_cell.get(cell, []))))
            for p in ev.get("patterns", []):
                (shown if by_pattern.get(p) else missing).append(("pattern `%s`" % p, len(by_pattern.get(p, []))))
            for p in ev.get("probes", []):
                (shown if probes.get(p) else missing).append(("probe `%s`" % p, len(probes.get(p, []))))
            status = "covered" if not missing else "gap" if not shown else "partly covered"
        counts[status] = counts.get(status, 0) + 1
        what = ("; ".join("%s (%d)" % s for s in shown) if shown else "") if status != "no shape" else c["no_shape_reason"]
        if c.get("note"):
            what = (what + ". " if what else "") + c["note"]
        gap = "; ".join(m for m, _ in missing)
        if gap:
            gap += (". Planned: " + c["planned"]) if c.get("planned") else ""
        rows.append("| %s | %s | %s | %s | %s | %s |" % (c["cap"], c["protocol"], c["title"].replace("|", "/"), status, what,
                                                          gap or "—"))
    lines = ["# Per-CAP coverage", "",
             "Generated by `tools/cap_coverage.py` from `corpus/cap-coverage.json` and the manifest. Do not edit by hand.",
             "", "Every live CAP (Final or Implemented in stellar-protocol's `core/README.md`, retrieved 16 November "
             "2026): %d CAPs. %s." % (len(spec["caps"]), ", ".join("%d %s" % (counts[k], k) for k in
                                                                  ("covered", "partly covered", "gap", "no shape") if k in counts)),
             "", "The number after each piece of evidence is how many corpus entries contain it.", "",
             "| CAP | Protocol | Title | Status | Evidence in the corpus, or why there is no shape | Gap |",
             "|---|---|---|---|---|---|"] + rows
    dated = CORPUS / "cell-protocols.json"
    if dated.exists():
        cp = json.load(open(dated))
        have = set(by_cell)
        order = list(cp["tags"])
        per = {t: [0, 0] for t in order}
        for cell, tag in cp["first_tag"].items():
            per[tag][0] += 1
            per[tag][1] += cell in have
        labels = {"v19": "19 or earlier", "v30.0": "29 or 30"}
        checks = cp["cap_tag_checks"]
        lines += ["", "## Schema cells by the protocol that introduced them", "",
                  "Each cell (union arm or enum member) of the protocol 30 schema, dated to the first stellar/stellar-xdr "
                  "tag that has it (`tools/cell_protocols.py`, `corpus/cell-protocols.json`). There is no v29 tag, so "
                  "cells first seen in v30.0 came with protocol 29 or 30.", "",
                  "| First tag | Protocol | Cells introduced | In the corpus | Not in the corpus |", "|---|---|---|---|---|"]
        for t in order:
            if per[t][0]:
                lines.append("| %s | %s | %d | %d | %d |" % (t, labels.get(t, t[1:].split(".")[0]), per[t][0], per[t][1],
                                                           per[t][0] - per[t][1]))
        bad = [c for c in checks if not c["agrees"]]
        lines += ["", "The hand-assigned CAP of each cell in `corpus/cap-map.json` was checked against these dates: "
                  "%d of %d agree (a CAP's cells first appear in the protocol the CAP shipped in)%s" % (
                      len(checks) - len(bad), len(checks), "." if not bad else ". Disagreements:")]
        lines += ["- `%s`: tagged %s (protocol %s), first in %s" % (c["cell"], c["cap"], c["cap_protocol"], c["first_tag"])
                  for c in bad]
    text = "\n".join(lines) + "\n"
    out = CORPUS / "CAP-COVERAGE.md"
    if a.check:
        if not out.exists() or out.read_text() != text:
            errors.append("corpus/CAP-COVERAGE.md is out of date: run tools/cap_coverage.py")
    else:
        out.write_text(text)
    for e in errors:
        print("ERROR: " + e)
    print(lines[4])
    print("CAP COVERAGE OK" if not errors else "CAP COVERAGE FAILED")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
