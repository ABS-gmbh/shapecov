"""The guide's checklist evidence: for each checklist item, the corpus entries or sequences that
exercise it and the upstream fixes and issues where an indexer, SDK or exporter made that mistake.

Read from guide/evidence.json, harness/replay/backtest.json and FINDINGS.json; rendered into the guide
between the checklist-evidence markers by guide/check_guide.py, which also calls errors() below.
"""
import re

BEGIN = ("<!-- checklist-evidence:begin: generated by guide/check_guide.py --write from guide/evidence.json, "
         "the backtest and FINDINGS.json -->")
END = "<!-- checklist-evidence:end -->"
MAX_ENTRIES = 4


def checklist_numbers(guide_text, tables):
    """The item numbers of the guide's checklist table (header # | Check | ...)."""
    for head, rows in tables(guide_text):
        if head[:2] == ["#", "Check"]:
            return [r[0] for r in rows]
    return []


def _short(url):
    """A link's label: owner/repo#n for an issue or pull request, repo `abcdef12` for a commit."""
    m = re.match(r"https://github\.com/[^/]+/([^/]+)/(issues|pull)/(\d+)", url)
    if m:
        return "%s #%s" % (m.group(1), m.group(3))
    m = re.match(r"https://github\.com/[^/]+/([^/]+)/commit/([0-9a-f]{7,})", url)
    if m:
        return "%s `%s`" % (m.group(1), m.group(2)[:8])
    return url


def _backtest_link(item):
    if item["pipeline"] == "wallet-backend":
        if item["id"].startswith("wallet-backend#"):
            n = item["id"].split("#")[1]
            return "https://github.com/stellar/wallet-backend/pull/%s" % n
        return "https://github.com/stellar/wallet-backend/commit/%s" % item.get("fix", item["id"])
    owner_repo, n = item["issue"].split("#")
    return "https://github.com/%s/issues/%s" % (owner_repo, n)


def _finding_entries(rec):
    rep = rec.get("reproduction") or {}
    out = []
    if rep.get("corpus_entry"):
        out.append("`%s`" % rep["corpus_entry"])
    out += ["`%s`" % x for x in rep.get("also") or []]
    if rep.get("generated_case"):
        out.append("generated case `%s`" % rep["generated_case"])
    if rep.get("linter_report"):
        out.append("linter run on the indexer")
    if rep.get("evidence_file"):
        out.append("`%s`" % rep["evidence_file"])
    return out


def render(evidence, backtest, findings, known=None):
    """known: the corpus entry and sequence ids; a backtest entry outside them (a ledger of the sweep) is
    counted, not named."""
    items = {i["id"]: i for i in backtest["items"]}
    recs = {r["id"]: r for r in findings["findings"]}
    L = [BEGIN, "", "| # | Exercised by | Where an indexer, SDK or exporter got it wrong |", "|---|---|---|"]
    for num, ev in sorted(evidence["items"].items(), key=lambda kv: int(kv[0])):
        entries, links, sweep = ["`%s`" % e for e in ev.get("entries", [])], [], set()
        for bid in ev.get("backtest", []):
            it = items[bid]
            for e in it.get("entries") or []:
                if known is None or e["entry"] in known:
                    entries.append("`%s`" % e["entry"])
                else:
                    sweep.add(e["entry"])
            links.append(_backtest_link(it))
        for rid in ev.get("findings", []):
            entries += _finding_entries(recs[rid])
            links += recs[rid].get("upstream") or []
        seen, uniq = set(), []
        for e in entries:
            if e not in seen:
                seen.add(e)
                uniq.append(e)
        shown = ", ".join(uniq[:MAX_ENTRIES]) + (" and %d more" % (len(uniq) - MAX_ENTRIES) if len(uniq) > MAX_ENTRIES else "")
        if sweep:
            shown += ("; " if shown else "") + "%d ledger%s of the sweep" % (len(sweep), "" if len(sweep) == 1 else "s")
        lseen, labels = set(), []
        for u in links:
            if u not in lseen:
                lseen.add(u)
                labels.append("[%s](%s)" % (_short(u), u))
        L.append("| %s | %s | %s |" % (num, shown or "none in the corpus yet", ", ".join(labels) or "none recorded yet"))
    L += ["", END]
    return "\n".join(L)


def errors(evidence, backtest, findings, numbers, known=None):
    """Why guide/evidence.json disagrees with the backtest, the findings or the checklist. known: the corpus
    entry and sequence ids, which an item's own "entries" must be among."""
    items = {i["id"]: i for i in backtest["items"]}
    recs = {r["id"] for r in findings["findings"]}
    out = []
    for num in numbers:
        if num not in evidence["items"]:
            out.append("checklist item %s has no entry in guide/evidence.json" % num)
    for num, ev in evidence["items"].items():
        if num not in numbers:
            out.append("guide/evidence.json names checklist item %s, which the checklist does not have" % num)
        for bid in ev.get("backtest", []):
            if bid not in items:
                out.append("item %s cites backtest item %s, which harness/replay/backtest.json does not have" % (num, bid))
            elif items[bid]["verdict"] != "detected":
                out.append("item %s cites backtest item %s, whose verdict is %s, not detected" % (num, bid, items[bid]["verdict"]))
        for rid in ev.get("findings", []):
            if rid not in recs:
                out.append("item %s cites finding %s, which FINDINGS.json does not have" % (num, rid))
        for eid in ev.get("entries", []):
            if known is not None and eid not in known:
                out.append("item %s names corpus entry %s, which is neither in the manifest nor a sequence" % (num, eid))
    used = {b for ev in evidence["items"].values() for b in ev.get("backtest", [])}
    outside = evidence.get("outside_checklist") or {}
    for bid, it in items.items():
        if it["verdict"] == "detected" and bid not in used and bid not in outside:
            out.append("detected backtest item %s maps to no checklist item; add it to an item, or to outside_checklist "
                       "with a reason" % bid)
    return out
