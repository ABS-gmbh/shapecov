#!/usr/bin/env python3
"""Check that the indexer-hardening guide agrees with the corpus.

  python3 guide/check_guide.py            exit 0 if the guide agrees, 1 if not

Checks, all against corpus/patterns.json and corpus/manifest.json:

1. Every corpus pattern the guide names exists.
2. Every corpus pattern is named somewhere in the guide, so no known shape goes undocumented.
3. Every corpus entry ID the guide names exists in the manifest.
4. In every table with the columns "Corpus shape", "CAP" and "Entries":
   - "CAP" lists exactly the CAPs that patterns.json gives the row's patterns ("none" if none);
   - "Entries" gives, for each pattern of the row in order, how many manifest entries carry
     that pattern ("none yet" for zero).
5. Every row of the section 1 tables (columns "Checked" and "Not checked") has an entry in
   guide/verdicts.json, and each side of each row has evidence from stellar-core: probes (ids in
   guide/probes.json, each of whose outcome agrees with its expectation), corpus patterns with at
   least one entry, or an explicit "citation_only" reason ("nothing_claimed" for an empty cell).
   Every probe names a row of the tables. The guide's verdict table, between the
   core-verdicts markers, is exactly what this script renders from those two files.

  python3 guide/check_guide.py --write    regenerate the guide's verdict table, then check

Standard library only.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
GUIDE = os.path.join(HERE, "INDEXER-HARDENING.md")
VERDICTS = os.path.join(HERE, "verdicts.json")
PROBES = os.path.join(HERE, "probes.json")
BEGIN = "<!-- core-verdicts:begin: generated by guide/check_guide.py --write from verdicts.json and probes.json -->"
END = "<!-- core-verdicts:end -->"
SIDE_KEYS = {"probes", "corpus", "citation_only", "nothing_claimed"}

ENTRY_RE = re.compile(r"`((?:testnet|pubnet|golden|synthetic|localcore)-[a-z0-9-]+)`")
TICK_RE = re.compile(r"`([a-z0-9]+(?:-[a-z0-9]+)+)`")
CAP_RE = re.compile(r"CAP-\d{2,4}(?:-\d{2})?")


def norm_cap(c):
    """CAP-27, CAP-0027 -> CAP-0027; CAP-46-11 -> CAP-0046-11."""
    parts = c.split("-")
    parts[1] = parts[1].zfill(4)
    return "-".join(parts)


def tables(text):
    """Yield (header cells, [row cells]) for each markdown table."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        if lines[i].startswith("|") and i + 1 < len(lines) and re.match(r"^\|(\s*:?-+:?\s*\|)+\s*$", lines[i + 1]):
            head = [c.strip() for c in lines[i].strip().strip("|").split("|")]
            rows = []
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in re.split(r"(?<!\\)\|", lines[i].strip().strip("|"))])
                i += 1
            yield head, rows
        else:
            i += 1


def short(outcome):
    """A probe outcome for the guide: the fee amount is left out; it is not part of any claim."""
    return re.sub(r" \(fee charged: \d+ stroops\)", ", fee charged", outcome)


def side_status(side):
    if side.get("nothing_claimed"):
        return "none"
    if side.get("citation_only"):
        return "citation"
    return "core" if side.get("probes") or side.get("corpus") else "missing"


def render_side(side, probes):
    if side.get("nothing_claimed"):
        return "nothing claimed"
    parts = ["`%s`: %s" % (pid, short(probes[pid]["outcome"])) for pid in side.get("probes", []) if pid in probes]
    if side.get("corpus"):
        parts.append("core closed ledgers with %s" % ", ".join("`%s`" % c for c in side["corpus"]))
    if side.get("citation_only"):
        parts.append("**source citation only:** %s" % side["citation_only"])
    return "; ".join(parts)


def render(verdicts, probes_doc):
    probes = {p["id"]: p for p in probes_doc["probes"]}
    rows = verdicts["rows"]
    both = sum(1 for r in rows if {side_status(r["checked"]), side_status(r["not_checked"])} <= {"core", "none"})
    some = sum(1 for r in rows if "core" in (side_status(r["checked"]), side_status(r["not_checked"]))) - both
    only = len(rows) - both - some
    cited = [r["field"] for r in rows if "citation" in (side_status(r["checked"]), side_status(r["not_checked"]))]
    n_probes = sum(1 for p in probes_doc["probes"] if p["row"] != "(setup)")
    lines = [BEGIN, "",
             "**%d of %d rows** have a verdict from stellar-core itself on every side they make a claim about, "
             "**%d** on one side, and **%d** rest on the source citations alone. Rows with a side that has only a "
             "citation: %s." % (both, len(rows), some, only, "; ".join(cited) or "none"),
             "",
             "A probe is a transaction built to break, or to sit just inside, the rule: %d probes, plus %d setup "
             "transaction%s that deploy%s the native asset contract they call (`guide/probes.json` holds all %d "
             "records). `guide/probe_core.py` submits them to a local stellar-core %s at protocol %d, and CI runs it "
             "on every change. \"Core closed ledgers with\" names corpus patterns found in ledgers stellar-core "
             "closed, so core accepted that shape."
             % (n_probes, len(probes_doc["probes"]) - n_probes, "" if len(probes_doc["probes"]) - n_probes == 1 else "s",
                "s" if len(probes_doc["probes"]) - n_probes == 1 else "", len(probes_doc["probes"]),
                probes_doc["stellar_core"].split(" (")[0].replace("stellar-core ", ""), probes_doc["protocol"]),
             "",
             "| Field | Checked: what stellar-core did | Not checked: where stellar-core accepted it |",
             "|---|---|---|"]
    for r in rows:
        lines.append("| %s | %s | %s |" % (r["field"], render_side(r["checked"], probes),
                                           render_side(r["not_checked"], probes)))
    lines += ["", END]
    return "\n".join(lines)


def check_verdicts(text, patterns, carriers, errors, write=False):
    """Check 5. Returns the (possibly rewritten) guide text."""
    with open(VERDICTS) as f:
        verdicts = json.load(f)
    with open(PROBES) as f:
        probes_doc = json.load(f)
    probes = {p["id"]: p for p in probes_doc["probes"]}
    fields = []
    for head, rows in tables(text):
        if {"Checked", "Not checked"} <= set(head):
            fields += [r[0] for r in rows]
    vfields = [r["field"] for r in verdicts["rows"]]
    for f in sorted(set(fields) - set(vfields)):
        errors.append("guide row %r has no entry in guide/verdicts.json" % f)
    for f in sorted(set(vfields) - set(fields)):
        errors.append("guide/verdicts.json names row %r, which the guide's tables do not have" % f)
    for r in verdicts["rows"]:
        for name in ("checked", "not_checked"):
            side = r.get(name, {})
            extra = set(side) - SIDE_KEYS
            if extra:
                errors.append("row %r, %s: unknown keys %s" % (r["field"], name, sorted(extra)))
            if side_status(side) == "missing":
                errors.append("row %r, %s: no probe, no corpus pattern and no citation_only reason" % (r["field"], name))
            for pid in side.get("probes", []):
                if pid not in probes:
                    errors.append("row %r cites probe %s, which guide/probes.json does not have" % (r["field"], pid))
                elif not probes[pid]["agrees"]:
                    errors.append("probe %s: stellar-core's outcome %r does not match its expectation %r"
                                  % (pid, probes[pid]["outcome"], probes[pid]["expect"]))
            for c in side.get("corpus", []):
                if c not in patterns:
                    errors.append("row %r cites corpus pattern %s, which corpus/patterns.json does not define"
                                  % (r["field"], c))
                elif not carriers.get(c):
                    errors.append("row %r cites corpus pattern %s, which no corpus entry carries" % (r["field"], c))
    for p in probes_doc["probes"]:
        if p["row"] != "(setup)" and p["row"] not in fields:
            errors.append("probe %s names row %r, which the guide's tables do not have" % (p["id"], p["row"]))
    want = render(verdicts, probes_doc)
    if BEGIN not in text or END not in text:
        if write:
            errors.append("the guide has no core-verdicts markers; add %r and %r where the table belongs" % (BEGIN, END))
        else:
            errors.append("the guide has no verdict table (core-verdicts markers); run guide/check_guide.py --write")
        return text, verdicts
    a, rest = text.split(BEGIN, 1)
    got, b = rest.split(END, 1)
    if write:
        text = a + want + b
        with open(GUIDE, "w") as f:
            f.write(text)
    elif BEGIN + got + END != want:
        errors.append("the guide's verdict table is out of date; run guide/check_guide.py --write")
    return text, verdicts


def main():
    write = "--write" in sys.argv[1:]
    with open(os.path.join(REPO, "corpus", "patterns.json")) as f:
        patterns = json.load(f)["patterns"]
    with open(os.path.join(REPO, "corpus", "manifest.json")) as f:
        manifest = json.load(f)
    with open(GUIDE) as f:
        text = f.read()

    entry_ids = {e["id"] for e in manifest["entries"]}
    carriers = {p: [] for p in patterns}
    for e in manifest["entries"]:
        for x in e.get("patterns") or []:
            name = x if isinstance(x, str) else (x.get("pattern") or x.get("name"))
            carriers.setdefault(name, []).append(e["id"])

    errors = []
    named = set()
    for m in TICK_RE.finditer(text):
        tok = m.group(1)
        if tok in patterns:
            named.add(tok)
    # Tokens in "(Corpus: ...)" notes and "Corpus shape" cells must be patterns.
    claimed = set()
    for note in re.findall(r"\(Corpus: ([^)]*)\)", text):
        claimed.update(TICK_RE.findall(note))
    checked_rows = 0
    for head, rows in tables(text):
        if not {"Corpus shape", "CAP", "Entries"} <= set(head):
            continue
        ci, ki, ni = head.index("Corpus shape"), head.index("CAP"), head.index("Entries")
        for r in rows:
            if len(r) != len(head):
                errors.append("table row has %d cells, header has %d: %s" % (len(r), len(head), " | ".join(r)[:120]))
                continue
            pats = TICK_RE.findall(r[ci])
            claimed.update(pats)
            if not pats:
                continue
            checked_rows += 1
            unknown = [p for p in pats if p not in patterns]
            if unknown:
                continue  # reported below
            want_caps = sorted({norm_cap(c) for p in pats for c in patterns[p].get("caps", [])})
            got_caps = sorted({norm_cap(c) for c in CAP_RE.findall(r[ki])})
            if r[ki].strip().lower() in ("none", "—", "-", ""):
                got_caps = []
            if got_caps != want_caps:
                errors.append("row %s: CAP column says %s, patterns.json says %s"
                              % (", ".join(pats), got_caps or "none", want_caps or "none"))
            want_n = ["none yet" if not carriers.get(p) else str(len(carriers[p])) for p in pats]
            got_n = [x.strip() for x in r[ni].split(",")]
            if got_n != want_n:
                errors.append("row %s: Entries column says %r, the manifest has %r"
                              % (", ".join(pats), ", ".join(got_n), ", ".join(want_n)))
    for p in sorted(claimed - set(patterns)):
        errors.append("the guide names corpus pattern `%s`, which corpus/patterns.json does not define" % p)
    for p in sorted(set(patterns) - named):
        errors.append("corpus pattern `%s` is not mentioned anywhere in the guide" % p)
    for eid in sorted(set(ENTRY_RE.findall(text)) - entry_ids):
        errors.append("the guide names corpus entry `%s`, which is not in the manifest" % eid)
    text, verdicts = check_verdicts(text, patterns, carriers, errors, write=write)
    rows = verdicts["rows"]
    core_sides = sum(side_status(r[k]) == "core" for r in rows for k in ("checked", "not_checked"))
    claimed_sides = sum(side_status(r[k]) != "none" for r in rows for k in ("checked", "not_checked"))

    missing = sorted(p for p in patterns if not carriers.get(p))
    print("guide: %d patterns named, %d table rows checked against the manifest" % (len(named), checked_rows))
    print("guide: %d of %d claimed sides of the %d field rows have a verdict from stellar-core"
          % (core_sides, claimed_sides, len(rows)))
    if missing:
        print("patterns with no corpus entry yet: %s" % ", ".join(missing))
    for e in errors:
        print("ERROR: " + e)
    print("GUIDE OK" if not errors else "GUIDE DISAGREES WITH THE CORPUS (%d)" % len(errors))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
