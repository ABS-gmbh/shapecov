"""The guide's review gate, shared by guide/export_docs.py and guide/check_guide.py.

The guide's header carries one review line:

  **Review:** reviewer: —; role: —; date: —; commit reviewed: —

Empty (every field "—") until a stellar-core or platform engineer has reviewed the guide; then the
reviewer's own commit fills it: a name, a role, a date (YYYY-MM-DD) and the commit of this
repository they reviewed. While it is empty, the developers.stellar.org page the export writes
opens with a caution that the page has not been reviewed; once it is filled, with a "Reviewed by"
line instead. check_guide.py fails if the committed page and the review line disagree.

Also renders the generated part of guide/REVIEW.md: the rows whose stellar-core verdict rests on a
source citation alone, from verdicts.json and the guide's own tables and sources.
"""
import re

REVIEW_RE = re.compile(r"^\*\*Review:\*\* reviewer: (.*?); role: (.*?); date: (.*?); commit reviewed: (.*?)$", re.M)
EMPTY = "—"
CAUTION = ("<Warning>\n\n**Draft, not reviewed.** This page has not yet been reviewed by a stellar-core or platform "
           "engineer, which is the condition for publishing it. Do not rely on it until it has been.\n\n</Warning>\n")
CAUTION_MARK = "**Draft, not reviewed.**"
REVIEWED_MARK = "Reviewed by "
REPO_URL = "https://github.com/ABS-gmbh/shapecov"


def parse(text):
    """None while the review line is empty; a dict once it is filled. Raises ValueError when the line
    is missing, appears twice, is filled in part, or has a malformed date or commit."""
    found = REVIEW_RE.findall(text)
    if len(found) != 1:
        raise ValueError("the guide must have exactly one review line (**Review:** reviewer: ...; role: ...; "
                         "date: ...; commit reviewed: ...), it has %d" % len(found))
    values = [v.strip() for v in found[0]]
    if all(v == EMPTY for v in values):
        return None
    if any(v in (EMPTY, "") for v in values):
        raise ValueError("the review line is filled in part: %s" % "; ".join(values))
    reviewer, role, date, commit = values
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
        raise ValueError("the review date must be YYYY-MM-DD, not %r" % date)
    if not re.fullmatch(r"[0-9a-f]{7,40}", commit):
        raise ValueError("the commit reviewed must be a hex commit of this repository, not %r" % commit)
    return {"reviewer": reviewer, "role": role, "date": date, "commit": commit}


def page_opening(review):
    """What the exported page opens with: the caution, or the reviewed-by line."""
    if review is None:
        return CAUTION
    return ("%s%s (%s) on %s, at [`%s`](%s/commit/%s).\n"
            % (REVIEWED_MARK, review["reviewer"], review["role"], review["date"], review["commit"][:12],
               REPO_URL, review["commit"]))


def gate_errors(guide_text, page_text):
    """Why the committed page and the guide's review line disagree, as a list of messages."""
    try:
        review = parse(guide_text)
    except ValueError as e:
        return [str(e)]
    errors = []
    if review is None:
        if CAUTION_MARK not in page_text:
            errors.append("the review line is empty, but the exported page does not open with the not-reviewed caution")
        if REVIEWED_MARK in page_text:
            errors.append("the review line is empty, but the exported page says it was reviewed")
    else:
        if CAUTION_MARK in page_text:
            errors.append("the review line is filled, but the exported page still carries the not-reviewed caution")
        if page_opening(review).strip() not in page_text:
            errors.append("the review line is filled, but the exported page does not name that review")
        if "**Status: draft for review.**" in guide_text:
            errors.append("the review line is filled, but the guide's status still says draft for review")
    return errors


# --------------------------------------------------------------------- the brief's generated part

BRIEF_BEGIN = "<!-- citation-only:begin: generated by guide/check_guide.py --write from verdicts.json and the guide -->"
BRIEF_END = "<!-- citation-only:end -->"
SIDE_COLUMN = {"checked": "Checked", "not_checked": "Not checked"}
SIDE_WORDS = {"checked": "what stellar-core checks", "not_checked": "what stellar-core does not check"}


def sources(guide_text):
    """{number: text} from the guide's "### Sources" list."""
    m = re.search(r"^### Sources\n(.*?)(?=^## )", guide_text, re.M | re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        s = re.match(r"^(\d+)\. (.*)$", line)
        if s:
            out[int(s.group(1))] = s.group(2).strip()
    return out


def render_brief(verdicts, guide_text, tables, side_status):
    """The list of citation-only sides, each with the guide's statement and the sources it cites."""
    cells = {}
    for head, rows in tables(guide_text):
        if not {"Field", "Checked", "Not checked"} <= set(head):
            continue
        for r in rows:
            if len(r) == len(head):
                cells[r[head.index("Field")]] = {k: r[head.index(c)] for k, c in SIDE_COLUMN.items()}
    src = sources(guide_text)
    rows = verdicts["rows"]
    status = [(r, side, side_status(r[side])) for r in rows for side in ("checked", "not_checked")]
    cited = [(r["field"], side, r[side]["citation_only"]) for r, side, st in status if st == "citation"]
    core = sum(1 for _r, _s, st in status if st == "core")
    empty = sum(1 for _r, _s, st in status if st == "none")
    L = [BRIEF_BEGIN, "",
         "Section 1 has %d field rows, so %d sides (what stellar-core checks, what it does not). %d claim "
         "nothing; %d have a verdict from stellar-core itself, a probe or a ledger it closed; %d, in %d rows, "
         "rest on a source citation alone and are listed here." % (
             len(rows), 2 * len(rows), empty, core, len(cited), len({f for f, _s, _w in cited})), ""]
    for i, (field, side, why) in enumerate(cited, 1):
        statement = cells.get(field, {}).get(side, "(the row is missing from the guide's tables)")
        refs = sorted({int(n) for n in re.findall(r"\[(\d+)\]", statement)})
        L.append("%d. **%s**, %s. The guide says: %s" % (i, field, SIDE_WORDS[side], statement))
        L.append("   - Why there is no probe: %s." % why)
        for n in refs:
            L.append("   - Source [%d]: %s" % (n, src.get(n, "(not in the guide's source list)")))
        L.append("")
    L.append(BRIEF_END)
    return "\n".join(L)
