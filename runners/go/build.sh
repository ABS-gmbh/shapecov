#!/bin/sh
# Runs inside the golang image: resolves the SDK, generates the type registry from the SDK's
# own generated source, and builds a static Linux binary.
set -e
cd /work
[ -f go.mod ] || go mod init runner-go >/dev/null 2>&1
go get github.com/stellar/go-stellar-sdk@v0.9.0 >/dev/null 2>&1
DIR=$(go list -m -f '{{.Dir}}' github.com/stellar/go-stellar-sdk)
{
  echo "// Code generated by build.sh from the SDK's xdr_generated.go. DO NOT EDIT."
  echo "package main"
  echo 'import "github.com/stellar/go-stellar-sdk/xdr"'
  echo "var registry = map[string]func() interface{}{"
  grep -h -E '^type [A-Z][A-Za-z0-9]* ' "$DIR"/xdr/xdr_generated.go | awk '{print $2}' | sort -u | while read n; do
    echo "  \"$(echo "$n" | tr 'A-Z' 'a-z')\": func() interface{} { return new(xdr.$n) },"
  done
  echo "}"
} > registry.go
go mod tidy >/dev/null 2>&1
CGO_ENABLED=0 go build -o runner-go . && echo "built: $(grep -c 'func()' registry.go) types, sdk $(go list -m github.com/stellar/go-stellar-sdk)"
